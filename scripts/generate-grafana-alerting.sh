#!/bin/bash
# Generate Grafana alerting provisioning from .env settings
#
# Usage: ./scripts/generate-grafana-alerting.sh   (run by 'make install-grafana')
#
# Writes into grafana/provisioning/alerting/:
#   alert-rules.yml    rules for the active STACK (copied from templates/)
#   heartbeat.yml      always-firing heartbeat rule, when GRAFANA_HEARTBEAT_URL is set
#   notifications.yml  contact points + notification policy for what is enabled,
#                      and deletions for what is not
#
# Grafana keeps provisioned objects in its database after their file is gone,
# so turning a setting off has to delete them explicitly; otherwise a removed
# heartbeat would keep firing at an empty URL.
#
# URLs are not written to disk: the files reference $GRAFANA_ALERT_WEBHOOK_URL and
# $GRAFANA_HEARTBEAT_URL, which Grafana fills in from its container environment.
# Files are regenerated on every run; edit the templates instead.

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DIR="$(dirname "$SCRIPT_DIR")/grafana/provisioning/alerting"

STACK="${STACK:-vm}"
WEBHOOK_URL="${GRAFANA_ALERT_WEBHOOK_URL:-}"
WEBHOOK_TYPE="${GRAFANA_ALERT_WEBHOOK_TYPE:-slack}"
HEARTBEAT_URL="${GRAFANA_HEARTBEAT_URL:-}"

case "$WEBHOOK_TYPE" in
    slack|webhook) ;;
    *) echo "GRAFANA_ALERT_WEBHOOK_TYPE must be 'slack' or 'webhook', got '$WEBHOOK_TYPE'" >&2; exit 1 ;;
esac

if [ "$STACK" = "vm" ]; then
    cp "$DIR/templates/alert-rules-vm.yml" "$DIR/alert-rules.yml"
else
    cp "$DIR/templates/alert-rules-grafana.yml" "$DIR/alert-rules.yml"
fi

# contact-point.yml is from an earlier version of this setup.
rm -f "$DIR/contact-point.yml" "$DIR/heartbeat.yml"
if [ -n "$HEARTBEAT_URL" ]; then
    cp "$DIR/templates/heartbeat.yml" "$DIR/heartbeat.yml"
fi

{
    echo "# Generated by scripts/generate-grafana-alerting.sh - do not edit."
    echo "apiVersion: 1"

    # --- contact points -------------------------------------------------------
    if [ -n "$WEBHOOK_URL" ] || [ -n "$HEARTBEAT_URL" ]; then
        echo ""
        echo "contactPoints:"
    fi
    if [ -n "$WEBHOOK_URL" ]; then
        cat <<EOF
  - orgId: 1
    name: sib-alerts
    receivers:
      - uid: sib-alerts
        type: ${WEBHOOK_TYPE}
        settings:
          url: \$GRAFANA_ALERT_WEBHOOK_URL
EOF
    fi
    if [ -n "$HEARTBEAT_URL" ]; then
        cat <<'EOF'
  - orgId: 1
    name: sib-heartbeat
    receivers:
      - uid: sib-heartbeat
        type: webhook
        settings:
          url: $GRAFANA_HEARTBEAT_URL
          httpMethod: POST
EOF
    fi

    # --- notification policy ---------------------------------------------------
    if [ -z "$WEBHOOK_URL" ] && [ -z "$HEARTBEAT_URL" ]; then
        echo ""
        echo "# Nothing configured: back to Grafana's default policy."
        echo "resetPolicies:"
        echo "  - 1"
    else
        # The root needs a receiver even with only the heartbeat configured:
        # Grafana's built-in default email receiver is used then (it sends
        # nothing without SMTP). Policies use its receiver name, not its
        # "email receiver" display name.
        if [ -n "$WEBHOOK_URL" ]; then ROOT_RECEIVER="sib-alerts"; else ROOT_RECEIVER="grafana-default-email"; fi
        cat <<EOF

policies:
  - orgId: 1
    receiver: ${ROOT_RECEIVER}
    # Host alerts group per host; alerts without a host label share a group per rule.
    group_by: ['grafana_folder', 'alertname', 'hostname', 'host']
    group_wait: 30s
    group_interval: 5m
    repeat_interval: 4h
    routes:
EOF
        if [ -n "$HEARTBEAT_URL" ]; then
            cat <<'EOF'
      # Re-sent every 5 minutes while Grafana is up; the external monitor
      # alerts when the pings stop.
      - receiver: sib-heartbeat
        object_matchers: [['alertname', '=', 'SIB heartbeat']]
        group_by: ['alertname']
        group_wait: 0s
        group_interval: 1m
        repeat_interval: 5m
EOF
        fi
        if [ -n "$WEBHOOK_URL" ]; then
            cat <<'EOF'
      - receiver: sib-alerts
        object_matchers: [['severity', '=', 'critical']]
        group_wait: 10s
        group_interval: 1m
        repeat_interval: 1h
      - receiver: sib-alerts
        object_matchers: [['severity', '=', 'warning']]
        group_wait: 1m
        group_interval: 5m
        repeat_interval: 4h
EOF
        fi
    fi

    # --- remove what is turned off -----------------------------------------
    if [ -z "$HEARTBEAT_URL" ]; then
        echo ""
        echo "deleteRules:"
        echo "  - orgId: 1"
        echo "    uid: sib-heartbeat"
    fi
    if [ -z "$WEBHOOK_URL" ] || [ -z "$HEARTBEAT_URL" ]; then
        echo ""
        echo "deleteContactPoints:"
        if [ -z "$WEBHOOK_URL" ]; then printf '  - orgId: 1\n    uid: sib-alerts\n'; fi
        if [ -z "$HEARTBEAT_URL" ]; then printf '  - orgId: 1\n    uid: sib-heartbeat\n'; fi
    fi
} > "$DIR/notifications.yml"
